/** Friendly type name, Windows Explorer style ("PDF-document", "JPEG-afbeelding", "Bestandsmap"). */
export function typeName(item) {
  if (!item) return '';
  if (item.isDir) return t('ty_folder');
  const ext = (item.ext || '').toLowerCase();
  const EXT = (ext === 'jpg' ? 'JPEG' : ext).toUpperCase();
  if (EXT_TYPES[ext]) return t(EXT_TYPES[ext], { ext: EXT });
  const mime = item.mime || '';
  if (mime.startsWith('image/')) return EXT ? t('ty_image', { ext: EXT }) : t('ty_imageAny');
  if (mime.startsWith('audio/')) return t('ty_audio', { ext: EXT });
  if (mime.startsWith('video/')) return t('ty_video', { ext: EXT });
  if (!ext) return mime === 'application/x-executable' ? t('ty_program') : t('ty_file');
  return t('ty_ext', { ext: EXT });
}
