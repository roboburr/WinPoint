"""WinPoint as its own login session (13-11): GNOME Shell in the "winpoint" mode, and GNOME's own look elsewhere.

Robin (2026-11-13): "WinPoint als optie bij inloggen als keuze", "zodat nieuwe pc's netjes het kunnen installeren".
Run with --session-mode winpoint: the harness starts gnome-shell --mode=winpoint with the mode file that
scripts/install-session.py installs (generated by the same code, in a private system data dir) and with an empty
enabled-extensions, so only the mode can turn the extension on. Checks:

  mode        Main.sessionMode.currentMode is winpoint, its parent user, the extension is in the mode's list
  extension   win11-gnome@win11shell.local is ACTIVE although enabled-extensions is empty; Ubuntu's dock is not loaded
  shell       the native shell booted (the harness waited for it) and its windows are up
  start       the backend sets WinPoint's colour scheme at the start (a GNOME session may have put GNOME's back)
  record      WinPoint's writes to GNOME keys left gnome-look.json (host/src/gnome_look.rs) with GNOME's values
  restore     win11-app --gnome-look puts every key that still holds WinPoint's value back to GNOME's, and takes
              the caption-button blocks out of gtk.css (what the GnomeLook autostart does in GNOME and Ubuntu)

Run (from G):
    tools/heavy.sh --min-mb 2560 --tag session-mode -- python3 -B tests/gnome/harness.py launch run --lang nl \\
        --build-dir tests/build/session-release --source worktree --session-mode winpoint \\
        --scenario tests/gnome/scenarios/session-mode.py
"""
import json
import os
import subprocess

UUID = 'win11-gnome@win11shell.local'
MODE_JS = ("(()=>({current:Main.sessionMode.currentMode,parent:Main.sessionMode.parentMode,"
           "extensions:Main.sessionMode.enabledExtensions,"
           "state:Main.extensionManager.lookup('" + UUID + "')?.state??null,"
           "dock:Main.extensionManager.lookup('ubuntu-dock@ubuntu.com')?.state??null,"
           "userList:global.settings.get_strv('enabled-extensions')}))()")


def gsettings(h, verb, schema, key):
    """A GSettings value as GVariant text, read by GNOME Shell (the same keyfile backend as the session)."""
    assert verb == 'get'
    return h.eval(f"(()=>{{const Gio=imports.gi.Gio;return new Gio.Settings({{schema_id:'{schema}'}})"
                  f".get_value('{key}').print(true);}})()")


def run(h):
    h.record('boot', h.s.facts.get('nativeBoot'))
    h.sleep(4)
    mode = h.eval(MODE_JS)
    h.record('mode', mode)
    h.check('mode: winpoint with parent user', mode and mode.get('current') == 'winpoint' and mode.get('parent') == 'user',
            mode=mode)
    h.check('mode: the extension is in the mode list only', mode and UUID in (mode.get('extensions') or [])
            and UUID not in (mode.get('userList') or []), mode=mode)
    h.check('extension: ACTIVE through the mode', mode and mode.get('state') == 1, state=mode and mode.get('state'))
    h.check('extension: no Ubuntu dock', mode and mode.get('dock') in (None, 2, 6), dock=mode and mode.get('dock'))
    tops = h.s.native_state()
    h.check('shell: windows up', len(tops) >= 2, toplevels=[t.get('title') for t in tops])
    h.screenshot('session-desktop', settle=1.5)

    config = h.hm.RUN / 'config'
    record_path = config / 'win11-gnome' / 'gnome-look.json'
    # WinPoint's theme sync writes GNOME's interface keys when the theme changes: switch light and back
    settings = config / 'win11-gnome' / 'settings.json'
    data = json.loads(settings.read_text() or '{}')
    before = {key: gsettings(h, 'get', 'org.gnome.desktop.interface', key) for key in ('color-scheme', 'icon-theme', 'gtk-theme')}
    h.record('interface.before', before)
    h.check('start: WinPoint sets its colour scheme at the session start', before['color-scheme'] == "'prefer-dark'",
            before=before)
    data.setdefault('theme', {})['mode'] = 'light'
    settings.write_text(json.dumps(data, indent=2))
    h.sleep(3)
    winpoint = {key: gsettings(h, 'get', 'org.gnome.desktop.interface', key) for key in ('color-scheme', 'icon-theme', 'gtk-theme')}
    h.record('interface.winpoint', winpoint)
    try:
        record = json.loads(record_path.read_text())
    except (OSError, ValueError) as error:
        record = {'error': str(error)}
    h.record('record', record)
    keys = record.get('keys') or {}
    h.check('record: GNOME keys WinPoint wrote are kept', any(k.startswith('org.gnome.desktop.interface ') for k in keys),
            keys=sorted(keys))
    gtk_css = config / 'gtk-4.0' / 'gtk.css'
    h.record('gtk4.before', gtk_css.read_text()[:400] if gtk_css.is_file() else None)
    app = h.hm.RUN / 'prefix' / 'bin' / 'win11-app'
    out = subprocess.run([str(app), '--gnome-look'], env=dict(os.environ), capture_output=True, text=True, timeout=30)
    h.record('restore.exit', {'code': out.returncode, 'stderr': out.stderr[-400:]})
    after = {key: gsettings(h, 'get', 'org.gnome.desktop.interface', key) for key in ('color-scheme', 'icon-theme', 'gtk-theme')}
    h.record('interface.after', after)
    expected = {}
    for key in ('color-scheme', 'icon-theme', 'gtk-theme'):
        entry = keys.get(f'org.gnome.desktop.interface {key}')
        if entry and entry.get('winpoint') == winpoint[key]:
            expected[key] = entry.get('gnome')
    restored = all((after[k] == v) if v is not None else after[k] != winpoint[k] or winpoint[k] == before[k]
                   for k, v in expected.items())
    h.check('restore: GNOME values back', out.returncode == 0 and bool(expected) and restored,
            expected=expected, after=after, winpoint=winpoint)
    text = gtk_css.read_text() if gtk_css.is_file() else ''
    h.check('restore: no caption-button block in gtk-4.0/gtk.css', 'win11shell caption-buttons' not in text,
            gtk4=text[:400])
    data['theme']['mode'] = 'dark'
    settings.write_text(json.dumps(data, indent=2))
    h.sleep(2)
