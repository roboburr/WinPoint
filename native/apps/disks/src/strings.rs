/// The text of a key in the current language (the key itself when unknown).
pub fn s(key: &str) -> String {
    match STRINGS.iter().find(|(k, _, _)| *k == key) {
        Some((_, nl, en)) => kit::t(nl, en).to_owned(),
        None => key.to_owned(),
    }
}

/// `s(key)` with its placeholders filled: tf("freeOf", &[("f", ..), ("t", ..)]).
pub fn tf(key: &str, args: &[(&str, &str)]) -> String {
    fill(s(key), args)
}

/// A plural entry by `count` (one for 1, other for the rest, as Intl.PluralRules for nl and en), filled.
pub fn tp(key: &str, count: f64, args: &[(&str, &str)]) -> String {
    let form = if count == 1.0 { "one" } else { "other" };
    fill(s(&format!("{key}.{form}")), args)
}

fn fill(mut text: String, args: &[(&str, &str)]) -> String {
    for (k, v) in args {
        text = text.replace(&format!("{{{k}}}"), v);
    }
    text
}

